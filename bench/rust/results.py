"""Collects criterion's estimates from target/criterion into RESULTS.md.

    cargo bench --bench compare && python results.py
"""

import json
import pathlib
import platform

root = pathlib.Path(__file__).parent
groups = {}
for bench in sorted((root / "target" / "criterion").glob("*/*/new/benchmark.json")):
    meta = json.loads(bench.read_text())
    estimates = json.loads((bench.parent / "estimates.json").read_text())
    elements = (meta.get("throughput") or {}).get("Elements")
    groups.setdefault(meta["group_id"], []).append((meta["function_id"], estimates["mean"]["point_estimate"], elements))


def fmt(ns):
    return f"{ns / 1e6:,.2f} ms" if ns >= 1e6 else f"{ns / 1e3:,.1f} µs"


lines = [
    "# autodyne vs ndarray, Burn and CubeCL",
    "",
    f"Generated by `results.py` from `cargo bench --bench compare` (criterion means), {platform.processor() or platform.machine()},",
    "NVIDIA GeForce RTX 5070 Ti for the GPU rows (wgpu). Every case first checks that the libraries agree.",
    "",
    "- CPU rows marked \"1 thread\" run single-threaded; Burn's CPU backend (flex) may use several threads.",
    "- GPU \"resident\": data already on the GPU, timed until the device is idle. \"round trip\": upload, compute, download,",
    "  which is what a CPU caller pays.",
    "- Relative = autodyne's time / this row's time (above 1: faster than autodyne).",
    "",
]
for group, rows in groups.items():
    ours = next((t for name, t, _ in rows if name.startswith("autodyne")), None)
    lines += [f"## {group}", "", "| Library | Time | Throughput | Relative to autodyne |", "|---|---:|---:|---:|"]
    for name, t, elements in sorted(rows, key=lambda r: r[1]):
        rate = f"{elements / t:,.2f} Gelem/s" if elements else ""
        rel = f"{ours / t:.2f}x" if ours else ""
        lines.append(f"| {name} | {fmt(t)} | {rate} | {rel} |")
    lines.append("")
(root / "RESULTS.md").write_text("\n".join(lines), encoding="utf-8")
print("\n".join(lines))
